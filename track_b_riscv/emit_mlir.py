#!/usr/bin/env python3
"""
emit_mlir.py  (Track B, step 1)
===============================
Tsetlin Machine model (tm_model.json)  ->  standard MLIR (func + arith dialects)
                                       ->  golden.h (expected outputs, computed independently)

The MLIR produced here is *real* MLIR: it is checked by `mlir-opt` and lowered through
the LLVM dialect to an RV32I binary by build.sh. Nothing in this file decides which
RISC-V instructions are used -- that comes out of the compiler, and profile_isa.py
measures it.

Usage:
    python3 emit_mlir.py <tm_model.json> <out_dir>
"""
import json
import os
import sys


def literal_value(lit_index, x_bits):
    """Literal k: input k//2, negated when k is odd  ->  [x1, ~x1, x2, ~x2, ...]."""
    v = x_bits[lit_index // 2]
    return v ^ 1 if lit_index % 2 else v


def reference_eval(model, x_bits):
    """Independent golden model: evaluates include masks directly (not via MLIR)."""
    pos = neg = 0
    for c in model["clauses"]:
        mask = c["include_mask"]
        if sum(mask) == 0:
            out = 0
        else:
            out = int(all(literal_value(k, x_bits) for k, inc in enumerate(mask) if inc))
        if c["polarity"] == 1:
            pos += out
        else:
            neg += out
    return int(pos - neg >= 0)


def emit_mlir(model):
    n = model["num_inputs"]
    args = ", ".join(f"%x{i}: i1" for i in range(n))
    L = []
    L.append(f"// Tsetlin Machine '{model['benchmark_name']}' -- {n} inputs, "
             f"{len(model['clauses'])} clauses. Dialects: func, arith.")
    L.append("module {")
    L.append(f"  func.func @tm_infer({args}) -> i1 {{")
    L.append("    %true = arith.constant true")
    L.append("    %c0_i32 = arith.constant 0 : i32")

    # Literal generation: only materialise the negations that some clause uses.
    used = {k for c in model["clauses"] for k, inc in enumerate(c["include_mask"]) if inc}
    def lit_ssa(k):
        return f"%x{k // 2}" if k % 2 == 0 else f"%nx{k // 2}"
    for i in range(n):
        if (2 * i + 1) in used:
            L.append(f"    %nx{i} = arith.xori %x{i}, %true : i1")

    pos, neg = [], []
    for j, c in enumerate(model["clauses"]):
        lits = [k for k, inc in enumerate(c["include_mask"]) if inc]
        name = f"%cl{j}"
        if not lits:
            L.append(f"    {name} = arith.constant false   // empty clause")
        elif len(lits) == 1:
            L.append(f"    {name} = arith.andi {lit_ssa(lits[0])}, %true : i1")
        else:
            cur = lit_ssa(lits[0])
            for s, k in enumerate(lits[1:]):
                nxt = name if s == len(lits) - 2 else f"%cl{j}_{s}"
                L.append(f"    {nxt} = arith.andi {cur}, {lit_ssa(k)} : i1")
                cur = nxt
        L.append(f"    {name}_w = arith.extui {name} : i1 to i32   // {c.get('formula', '')}")
        (pos if c["polarity"] == 1 else neg).append(f"{name}_w")

    def sum_chain(vals, tag):
        if not vals:
            return "%c0_i32"
        cur = vals[0]
        for s, v in enumerate(vals[1:]):
            L.append(f"    %{tag}{s} = arith.addi {cur}, {v} : i32")
            cur = f"%{tag}{s}"
        return cur

    p = sum_chain(pos, "pos")
    q = sum_chain(neg, "neg")
    L.append(f"    %diff = arith.subi {p}, {q} : i32")
    L.append("    %decision = arith.cmpi sge, %diff, %c0_i32 : i32")
    L.append("    return %decision : i1")
    L.append("  }")
    L.append("}")
    return "\n".join(L) + "\n"


def emit_golden_header(model):
    n = model["num_inputs"]
    total = 1 << n
    exp = []
    for v in range(total):
        bits = [(v >> i) & 1 for i in range(n)]       # bit i -> x_i
        exp.append(reference_eval(model, bits))
    L = [f"// Golden outputs for '{model['benchmark_name']}', generated by emit_mlir.py",
         f"#define TM_NUM_INPUTS {n}",
         f"#define TM_NUM_VECTORS {total}",
         "static const unsigned char tm_expected[TM_NUM_VECTORS] = {",
         "  " + ", ".join(map(str, exp)),
         "};"]
    return "\n".join(L) + "\n"


def emit_c_prototype(model):
    n = model["num_inputs"]
    args = ", ".join("_Bool" for _ in range(n))
    return (f"// Prototype of the MLIR-compiled kernel\n"
            f"_Bool tm_infer({args});\n"
            f"#define TM_CALL(b) tm_infer({', '.join(f'(b)[{i}]' for i in range(n))})\n")


def main():
    model_path, out_dir = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    with open(model_path) as f:
        model = json.load(f)
    with open(os.path.join(out_dir, "workload.mlir"), "w") as f:
        f.write(emit_mlir(model))
    with open(os.path.join(out_dir, "golden.h"), "w") as f:
        f.write(emit_golden_header(model))
        f.write(emit_c_prototype(model))
    print(f"[emit_mlir] {model['benchmark_name']}: workload.mlir + golden.h -> {out_dir}")


if __name__ == "__main__":
    main()
