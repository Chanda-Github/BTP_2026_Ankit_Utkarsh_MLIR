#!/usr/bin/env python3
"""
emit_mlir.py  (Track B, step 1)
===============================
Tsetlin Machine model (tm_model.json)  ->  standard MLIR (func + arith dialects)
                                       ->  golden.h (expected outputs, computed independently)

The MLIR produced here is *real* MLIR: it is checked by `mlir-opt` and lowered through
the LLVM dialect to an RV32I binary by build.sh. Nothing in this file decides which
RISC-V instructions are used -- that comes out of the compiler, and profile_isa.py
measures it.

Usage:
    python3 emit_mlir.py <tm_model.json> <out_dir>
"""
import json
import os
import sys


def literal_value(lit_index, x_bits):
    """Literal k: input k//2, negated when k is odd  ->  [x1, ~x1, x2, ~x2, ...]."""
    v = x_bits[lit_index // 2]
    return v ^ 1 if lit_index % 2 else v


def reference_eval(model, x_bits):
    """Independent golden model: evaluates include masks directly (not via MLIR)."""
    pos = neg = 0
    for c in model["clauses"]:
        mask = c["include_mask"]
        if sum(mask) == 0:
            out = 0
        else:
            out = int(all(literal_value(k, x_bits) for k, inc in enumerate(mask) if inc))
        if c["polarity"] == 1:
            pos += out
        else:
            neg += out
    return int(pos - neg >= 0)


def emit_mlir(model):
    n = model["num_inputs"]
    args = ", ".join(f"%x{i}: i1" for i in range(n))
    L = []
    L.append(f"// Tsetlin Machine '{model['benchmark_name']}' -- {n} inputs, "
             f"{len(model['clauses'])} clauses. Dialects: func, arith.")
    L.append("module {")
    L.append(f"  func.func @tm_infer({args}) -> i1 {{")
    L.append("    %true = arith.constant true")
    L.append("    %c0_i32 = arith.constant 0 : i32")

    # Literal generation: only materialise the negations that some clause uses.
    used = {k for c in model["clauses"] for k, inc in enumerate(c["include_mask"]) if inc}
    def lit_ssa(k):
        return f"%x{k // 2}" if k % 2 == 0 else f"%nx{k // 2}"
    for i in range(n):
        if (2 * i + 1) in used:
            L.append(f"    %nx{i} = arith.xori %x{i}, %true : i1")

    pos, neg = [], []
    for j, c in enumerate(model["clauses"]):
        lits = [k for k, inc in enumerate(c["include_mask"]) if inc]
        name = f"%cl{j}"
        if not lits:
            L.append(f"    {name} = arith.constant false   // empty clause")
        elif len(lits) == 1:
            L.append(f"    {name} = arith.andi {lit_ssa(lits[0])}, %true : i1")
        else:
            cur = lit_ssa(lits[0])
            for s, k in enumerate(lits[1:]):
                nxt = name if s == len(lits) - 2 else f"%cl{j}_{s}"
                L.append(f"    {nxt} = arith.andi {cur}, {lit_ssa(k)} : i1")
                cur = nxt
        L.append(f"    {name}_w = arith.extui {name} : i1 to i32   // {c.get('formula', '')}")
        (pos if c["polarity"] == 1 else neg).append(f"{name}_w")

    def sum_chain(vals, tag):
        if not vals:
            return "%c0_i32"
        cur = vals[0]
        for s, v in enumerate(vals[1:]):
            L.append(f"    %{tag}{s} = arith.addi {cur}, {v} : i32")
            cur = f"%{tag}{s}"
        return cur

    p = sum_chain(pos, "pos")
    q = sum_chain(neg, "neg")
    L.append(f"    %diff = arith.subi {p}, {q} : i32")
    L.append("    %decision = arith.cmpi sge, %diff, %c0_i32 : i32")
    L.append("    return %decision : i1")
    L.append("  }")
    L.append("}")
    return "\n".join(L) + "\n"


def emit_golden_header(model):
    n = model["num_inputs"]
    total = 1 << n
    exp = []
    for v in range(total):
        bits = [(v >> i) & 1 for i in range(n)]       # bit i -> x_i
        exp.append(reference_eval(model, bits))
    L = [f"// Golden outputs for '{model['benchmark_name']}', generated by emit_mlir.py",
         f"#define TM_NUM_INPUTS {n}",
         f"#define TM_NUM_VECTORS {total}",
         "static const unsigned char tm_expected[TM_NUM_VECTORS] = {",
         "  " + ", ".join(map(str, exp)),
         "};"]
    return "\n".join(L) + "\n"


def emit_c_prototype(model):
    n = model["num_inputs"]
    args = ", ".join("_Bool" for _ in range(n))
    return (f"// Prototype of the MLIR-compiled kernel\n"
            f"_Bool tm_infer({args});\n"
            f"#define TM_CALL(b) tm_infer({', '.join(f'(b)[{i}]' for i in range(n))})\n")


# ---------------------------------------------------------------------------------------------
# Multi-class models (format tm_multiclass_v1, e.g. imported by import_codalab.py)
# ---------------------------------------------------------------------------------------------
# Semantics follow the CoDALab TM/standard.cpp predict():
#   literal k < F is x_k, literal k >= F is ~x_{k-F}          (concatenated order)
#   votes[c] = C + #(firing clauses j < C/2) - #(firing clauses j >= C/2); empty clauses never fire
#   result   = first class with the strictly largest vote      (ties -> lowest class index)
# Inputs arrive as a byte array in memory (one byte per feature), as on the CoDALab RISC-V core.

def reference_eval_multiclass(model, x):
    F, C = model["num_features"], model["clauses_per_class"]
    lit = list(x) + [1 - v for v in x]
    best, best_v = 0, 0
    for c, clauses in enumerate(model["classes"]):
        v = C
        for j, inc in enumerate(clauses):
            if inc and all(lit[k] for k in inc):
                v += 1 if j < C // 2 else -1
        if v > best_v:
            best, best_v = c, v
    return best


def emit_mlir_multiclass(model):
    F, C = model["num_features"], model["clauses_per_class"]
    used = sorted({k for cl in model["classes"] for inc in cl for k in inc})
    feats = sorted({k % F for k in used})
    L = [f"// Tsetlin Machine '{model['benchmark_name']}' -- {F} features, "
         f"{model['num_classes']} classes x {C} clauses. Dialects: func, arith, memref.",
         f"// Source: {model.get('source', 'n/a')}",
         "module {",
         f"  func.func @tm_infer(%x: memref<{F}xi8>) -> i32 {{",
         "    %true = arith.constant true",
         "    %c0_i32 = arith.constant 0 : i32"]
    # Load each feature that some clause uses, once; materialise only the negations used.
    for f in feats:
        L.append(f"    %i{f} = arith.constant {f} : index")
        L.append(f"    %b{f} = memref.load %x[%i{f}] : memref<{F}xi8>")
        L.append(f"    %x{f} = arith.trunci %b{f} : i8 to i1")
    for k in used:
        if k >= F:
            L.append(f"    %nx{k - F} = arith.xori %x{k - F}, %true : i1")

    def lit(k):
        return f"%x{k}" if k < F else f"%nx{k - F}"

    best, best_v = "%c0_i32", "%c0_i32"
    for c, clauses in enumerate(model["classes"]):
        L.append(f"    // ---- class {c} ----")
        L.append(f"    %base{c} = arith.constant {C} : i32")
        pos, neg = [], []
        for j, inc in enumerate(clauses):
            if not inc:
                continue                       # empty clause never fires: no hardware, no code
            cur = lit(inc[0])
            for s, k in enumerate(inc[1:]):
                nxt = f"%k{c}_{j}" if s == len(inc) - 2 else f"%k{c}_{j}_{s}"
                L.append(f"    {nxt} = arith.andi {cur}, {lit(k)} : i1")
                cur = nxt
            if len(inc) == 1:
                L.append(f"    %k{c}_{j} = arith.andi {cur}, %true : i1")
            L.append(f"    %w{c}_{j} = arith.extui %k{c}_{j} : i1 to i32")
            (pos if j < C // 2 else neg).append(f"%w{c}_{j}")
        acc = f"%base{c}"
        for t, w in enumerate(pos):
            L.append(f"    %p{c}_{t} = arith.addi {acc}, {w} : i32")
            acc = f"%p{c}_{t}"
        for t, w in enumerate(neg):
            L.append(f"    %n{c}_{t} = arith.subi {acc}, {w} : i32")
            acc = f"%n{c}_{t}"
        # argmax, strictly-greater update (ties keep the lower class)
        L.append(f"    %cls{c} = arith.constant {c} : i32")
        L.append(f"    %gt{c} = arith.cmpi sgt, {acc}, {best_v} : i32")
        L.append(f"    %bv{c} = arith.select %gt{c}, {acc}, {best_v} : i32")
        L.append(f"    %bc{c} = arith.select %gt{c}, %cls{c}, {best} : i32")
        best, best_v = f"%bc{c}", f"%bv{c}"
    L += [f"    return {best} : i32", "  }", "}"]
    return "\n".join(L) + "\n"


def emit_golden_header_multiclass(model):
    F = model["num_features"]
    inputs = [[int(ch) for ch in row] for row in model["test_inputs"]]
    expected = [reference_eval_multiclass(model, x) for x in inputs]
    if "reference_predictions" in model:   # two independent implementations must agree
        assert expected == model["reference_predictions"], "golden model disagrees with importer"
    L = [f"// Golden outputs for '{model['benchmark_name']}', generated by emit_mlir.py",
         "#define TM_MULTICLASS 1",
         f"#define TM_NUM_FEATURES {F}",
         f"#define TM_NUM_VECTORS {len(inputs)}",
         "static const unsigned char tm_inputs[TM_NUM_VECTORS][TM_NUM_FEATURES] = {"]
    L += ["  {" + ",".join(map(str, x)) + "}," for x in inputs]
    L += ["};",
          "static const unsigned char tm_expected[TM_NUM_VECTORS] = {",
          "  " + ", ".join(map(str, expected)),
          "};",
          "// MLIR-compiled kernel (static memref passed as a bare pointer)",
          "int tm_infer(const unsigned char *x);"]
    return "\n".join(L) + "\n"


def main():
    model_path, out_dir = sys.argv[1], sys.argv[2]
    os.makedirs(out_dir, exist_ok=True)
    with open(model_path) as f:
        model = json.load(f)
    multiclass = model.get("format") == "tm_multiclass_v1"
    with open(os.path.join(out_dir, "workload.mlir"), "w") as f:
        f.write(emit_mlir_multiclass(model) if multiclass else emit_mlir(model))
    with open(os.path.join(out_dir, "golden.h"), "w") as f:
        if multiclass:
            f.write(emit_golden_header_multiclass(model))
        else:
            f.write(emit_golden_header(model))
            f.write(emit_c_prototype(model))
    print(f"[emit_mlir] {model['benchmark_name']}: workload.mlir + golden.h -> {out_dir}")


if __name__ == "__main__":
    main()
