#!/usr/bin/env python3
"""
compare_with_paper.py -- same model, same input, same core: paper flow vs MLIR flow
==================================================================================
For each case (dataset, clauses, T1/T2) and each core (R1, R2):

  paper image : the lab's own Tests/<ds>/<C>/memory{i,d}.mem (T1) or Tests/<ds>_opt/<C>/ (T2),
                produced by the manual flow (gcc -> edited assembly -> online assembler,
                create_memory_*.cpp) and used for the ISVLSI'26 Vivado simulations
  MLIR image  : generated by this flow for the SAME model and the SAME test sample (both read
                back out of the paper's memoryd.mem)
  golden      : votes and class computed directly from the clauses in Python

Both images run on the lab's R1/R2 Verilog (Icarus, testbench riscv_tcm_top_tb.v). After each
run the votes[] array and DMEM[0] (predicted class) are read out of data memory, so the
comparison covers every class sum, not only the final class.

Usage:
    python3 compare_with_paper.py <codalab_repo_root> [ds/C/t1|t2 ...] [--cores r1,r2]
    default cases: a quick set that finishes in ~15 minutes
Writes out/compare/REPORT.md
"""
import argparse
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TRACK = os.path.dirname(HERE)
sys.path.insert(0, TRACK)
from import_codalab import read_mem_bytes, word, decode_model  # noqa: E402

DEFAULT_CASES = ["iris/4/t1", "iris/4/t2", "mammography/10/t1", "mammography/50/t2",
                 "statlog/100/t2", "har/200/t2"]


# ---------------------------------------------------------------------------------------------
# Reading the paper's data-memory images (layouts of create_memory_standard/optimized.cpp)
# ---------------------------------------------------------------------------------------------
def pad4(n):
    return (n + 3) // 4 * 4


def paper_t1_layout(mem_path):
    mem = read_mem_bytes(mem_path)
    K, C, L = word(mem, 4), word(mem, 12), word(mem, 16)
    lit = list(mem[20:20 + L])
    votes = 20 + pad4(L) + 4 * K + 4 * K * C + pad4(K * C * L) + 4 * K + pad4(K * C)
    return {"K": K, "C": C, "L": L, "lit": lit, "votes_addr": votes}


def paper_t2_layout(mem_path, L):
    """T2 header has no literal count; L comes from the model. Also decodes the clauses."""
    mem = read_mem_bytes(mem_path)
    K, C = word(mem, 4), word(mem, 12)
    lit = list(mem[16:16 + L])
    p = 16 + pad4(L)
    count_tbl = p
    counts = []
    for i in range(K):
        base = word(mem, count_tbl + 4 * i)
        counts.append([int.from_bytes(mem[base + 2 * j: base + 2 * j + 2], "little") for j in range(C)])
    p = count_tbl + 4 * K + 4 * K * (C // 2)
    off_tbl = p
    classes = []
    for i in range(K):
        clause_tbl = word(mem, off_tbl + 4 * i)
        cl = []
        for j in range(C):
            a = word(mem, clause_tbl + 4 * j)
            cl.append([int.from_bytes(mem[a + 2 * k: a + 2 * k + 2], "little") for k in range(counts[i][j])])
        classes.append(cl)
    n_off = sum(map(sum, counts))
    votes = off_tbl + 4 * K + 4 * K * C + 2 * (n_off + (n_off % 2))
    return {"K": K, "C": C, "L": L, "lit": lit, "votes_addr": votes, "classes": classes}


# ---------------------------------------------------------------------------------------------
# Golden model
# ---------------------------------------------------------------------------------------------
def golden(classes, C, lit, paper_swap=False):
    """paper_swap=False: TM/standard.cpp semantics (the trained model).
    paper_swap=True : what the hand-edited assembly computes after 'bge x,y -> blt y,x':
                      clause j == C/2 votes +1 (should be -1) and argmax ties go to the last class."""
    votes = []
    for cl in classes:
        v = C
        for j, inc in enumerate(cl):
            if inc and all(lit[k] for k in inc):
                pos = (j <= C // 2) if paper_swap else (j < C // 2)
                v += 1 if pos else -1
        votes.append(v)
    best, bv = 0, 0
    for i, v in enumerate(votes):
        if v > bv or (paper_swap and v == bv and i > 0):
            best, bv = i, v
    return votes, best


# ---------------------------------------------------------------------------------------------
def sh(cmd, env=None):
    e = dict(os.environ)
    e.update(env or {})
    return subprocess.run(cmd, shell=True, capture_output=True, text=True, env=e)


def run_rtl(root, core, mem_dir, env):
    sh(f'"{HERE}/sim_rtl.sh" "{root}" {core} "{mem_dir}"', env)
    log = open(os.path.join(mem_dir, "rtl_sim.log")).read()
    m = re.search(r"Result Store Cycle: (\d+)", log)
    res = re.search(r"Addr 0x00000000: 0x[0-9a-fA-F]+ \((-?\d+)\)", log)
    votes = [int(v) for v in re.findall(r"DUMP addr=\d+ value=(-?\d+)", log)]
    return {"cycles": int(m.group(1)) if m else None,
            "result": int(res.group(1)) if res else None, "votes": votes}


def symbol(elf, name):
    out = sh(f"/usr/lib/llvm-18/bin/llvm-nm {elf}").stdout
    for line in out.splitlines():
        p = line.split()
        if len(p) == 3 and p[2] == name:
            return int(p[0], 16)
    raise SystemExit(f"{name} not in {elf}")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("root")
    ap.add_argument("cases", nargs="*")
    ap.add_argument("--cores", default="r1,r2")
    ap.add_argument("--out", default=os.path.join(TRACK, "out", "compare"))
    a = ap.parse_args()
    cases = a.cases or DEFAULT_CASES
    cores = a.cores.split(",")
    os.makedirs(a.out, exist_ok=True)
    rows = []

    for case in cases:
        ds, C, var = case.split("/")
        tests = os.path.join(a.root, "Tests", ds if var == "t1" else ds + "_opt", C)
        std_mem = os.path.join(a.root, "Tests", ds, C, "memoryd.mem")
        K, Cn, L, classes = decode_model(std_mem)           # model from the paper's T1 image
        if var == "t1":
            lay = paper_t1_layout(os.path.join(tests, "memoryd.mem"))
        else:
            lay = paper_t2_layout(os.path.join(tests, "memoryd.mem"), L)
            assert lay["classes"] == classes, f"{case}: T2 image holds a different model than T1"
        lit = lay["lit"]
        F = L // 2
        g_votes, g_class = golden(classes, Cn, lit)
        s_votes, s_class = golden(classes, Cn, lit, paper_swap=True)

        # MLIR image for the same model and the same sample
        model_path = os.path.join(TRACK, "models", "codalab", f"{ds}_{C}.json")
        model = json.load(open(model_path))
        rows_in = [[int(ch) for ch in r] for r in model["test_inputs"]]
        try:
            sample = rows_in.index(lit[:F])
        except ValueError:
            raise SystemExit(f"{case}: paper's stored sample not among the first test rows")
        work = os.path.join(a.out, f"{ds}_{C}_{var}")
        r = sh(f'"{HERE}/run_core_flow.sh" "{model_path}" {var} "{work}"', {"SAMPLE": str(sample)})
        if r.returncode:
            print(r.stdout, r.stderr)
            raise SystemExit(f"{case}: MLIR flow failed")

        for core in cores:
            # paper image: stop at the jump back to PC 0, read votes from its layout
            pdir = os.path.join(work, f"paper_{core}")
            os.makedirs(pdir, exist_ok=True)
            for f in ("memoryi.mem", "memoryd.mem"):
                with open(os.path.join(tests, f)) as src, open(os.path.join(pdir, f), "w") as dst:
                    dst.write(src.read())
            paper = run_rtl(a.root, core, pdir, {"RESTART_STOP": "1", "DUMP_ADDR": str(lay["votes_addr"]),
                                                 "DUMP_WORDS": str(K), "MAX_CYCLES": "30000000"})
            # MLIR image: stops at its single result store, votes at symbol tm_votes
            mdir = os.path.join(work, core)
            vaddr = symbol(os.path.join(work, f"core_{core}.elf"), "tm_votes")
            mlir = run_rtl(a.root, core, mdir, {"DUMP_ADDR": str(vaddr), "DUMP_WORDS": str(K),
                                                "MAX_CYCLES": "30000000"})
            row = {"case": case, "core": core, "sample": sample, "golden_class": g_class,
                   "golden_votes": g_votes, "swap_class": s_class, "swap_votes": s_votes,
                   "paper": paper, "mlir": mlir}
            rows.append(row)
            if paper["result"] == g_class and paper["votes"] == g_votes:
                ok_p = "OK"
            elif paper["result"] == s_class and paper["votes"] == s_votes:
                ok_p = "= bge-swap semantics"
            else:
                ok_p = "DIFF (unexplained)"
            row["paper_status"] = ok_p
            ok_m = "OK" if mlir["result"] == g_class and mlir["votes"] == g_votes else "DIFF"
            print(f"{case:<20} {core}  golden class {g_class} votes {g_votes}\n"
                  f"{'':<24}paper: class {paper['result']} votes {paper['votes']} "
                  f"cycles {paper['cycles']}  [{ok_p}]\n"
                  f"{'':<24}MLIR : class {mlir['result']} votes {mlir['votes']} "
                  f"cycles {mlir['cycles']}  [{ok_m}]", flush=True)

    json.dump(rows, open(os.path.join(a.out, "compare.json"), "w"), indent=2)
    L_ = ["# Paper flow vs MLIR flow on the same core (Icarus, lab testbench)", "",
          "Same trained model, same input sample (the one stored in the paper's memoryd.mem), same "
          "R1/R2 Verilog. Votes are read from data memory after each run; golden = computed directly "
          "from the clauses.", "",
          "Paper status: `OK` = equals the golden model; `= bge-swap semantics` = equals exactly what "
          "the hand-edited assembly computes after rewriting `bge x,y` as `blt y,x` (clause C/2 votes "
          "+1 instead of -1, ties go to the last class), which the golden model also predicts.", "",
          "| Case | Core | Golden class | Paper class | MLIR class | Golden votes | Paper votes | MLIR votes "
          "| Paper status | Paper cycles | MLIR cycles | Speed-up |",
          "|---|---|:-:|:-:|:-:|---|---|---|---|---:|---:|---:|"]
    for r in rows:
        p, m = r["paper"], r["mlir"]
        sp = f"{p['cycles'] / m['cycles']:.1f}x" if p["cycles"] and m["cycles"] else "-"
        L_.append(f"| {r['case']} | {r['core'].upper()} | {r['golden_class']} | {p['result']} | "
                  f"{m['result']} | {r['golden_votes']} | {p['votes']} | {m['votes']} | "
                  f"{r['paper_status']} | {p['cycles']:,} | {m['cycles']:,} | {sp} |")
    open(os.path.join(a.out, "REPORT.md"), "w").write("\n".join(L_) + "\n")
    print(f"\nReport: {os.path.join(a.out, 'REPORT.md')}")


if __name__ == "__main__":
    main()
